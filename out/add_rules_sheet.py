"""Добавляет в итоговый файл лист «Правила и проверки»."""
import sys, subprocess
import openpyxl
from openpyxl.styles import Font, Alignment, PatternFill

OUT, IN, HR = sys.argv[1], sys.argv[2], sys.argv[3]
chk = subprocess.run([sys.executable, "-I", "check_timesheet_oct.py", IN, OUT], capture_output=True, text=True).stdout
tgt = subprocess.run([sys.executable, "-I", "targets_sep_vs_oct.py", IN, HR, OUT], capture_output=True, text=True).stdout

wb = openpyxl.load_workbook(OUT)
if "Правила и проверки" in wb.sheetnames:
    del wb["Правила и проверки"]
ws = wb.create_sheet("Правила и проверки", 1)
B = Font(bold=True); H = Font(bold=True, size=12)
fill = PatternFill("solid", fgColor="DDEBF7")
r = 1
def put(vals, font=None, bg=None):
    global r
    for j, v in enumerate(vals):
        c = ws.cell(row=r, column=j + 1, value=v)
        c.alignment = Alignment(wrap_text=True, vertical="top")
        if font: c.font = font
        if bg: c.fill = bg
    r += 1

put(["Правила распределения задач (октябрь 2026)"], H)
rules = [
    ("Номер задачи", "ADTHPL-N, N = номер строки листа «Задачи» каталога + 99 (как в сентябре). Наименования — с учетом файла «Задачи на замену»."),
    ("Должность", "Задачи — по должности сотрудника из каталога, активные в октябре. «Начальник отдела» = руководитель команды, «Специалист ML» = ведущий специалист ML."),
    ("Доли CAPEX/OPEX", "Продакты 60/40; руководители команд 30/70; директор, руководители управлений/направлений, менеджеры и руководители проектов, инженеры сопровождения, Гряда («нет в Jira») — 100% OPEX; остальные — 100% CAPEX."),
    ("≥ 2 CAPEX-задач", "У каждого сотрудника с CAPEX — не менее двух CAPEX-задач: основная ~70%, вторая ~30% (кратно 8 ч, не менее 16 ч). У 100% OPEX — одна задача, как в сентябре (вторая — только если основная упирается в лимит 350 ч)."),
    ("Лимит задачи", "Не более 350 ч на задачу в месяц по всем сотрудникам."),
    ("Ёмкость по срокам", "По задаче — не более 8 ч × ставка × рабочие дни сотрудника в периоде работ; на любом отрезке дат сумма часов задач, чей период внутри отрезка, — не более 8 ч × ставка × рабочие дни (нет параллельной перегрузки)."),
    ("Даты работ", "Срок задачи, обрезанный по октябрю; отпуск в начале/конце периода сдвигает даты; отпуск в середине — нет."),
    ("Преемственность", "Задачи сентября, которые идут в октябре, сохраняются; квартальные OPEX (3 кв.) → те же задачи 4 кв."),
    ("Новые задачи", "Сначала незанятые/наименее загруженные задачи (покрытие каталога); вторая CAPEX-задача — из того же эпика."),
    ("Соседний грейд", "Если своих задач не хватает по срокам (задачи начинаются позже 1 октября) — CAPEX-задачи той же профессии соседнего грейда с тем же видом работ (5 тестировщиков)."),
    ("Исключение", "Клименко: у должности одна CAPEX-задача в октябре; вторая — ADTHPL-202 «Дедупликация: приемка и подготовка к запуску» (вывод в промышленную среду)."),
    ("CAPEX и IAS 38", "Все CAPEX-работы — внутри окна эпика «начало капитализации — готовность к использованию»."),
]
put(["Правило", "Содержание"], B, fill)
for a, b in rules:
    put([a, b])
r += 1
put(["Результат проверок (скрипт check_timesheet_oct.py)"], H)
for line in chk.splitlines():
    if line.startswith(("OK", "FAIL", "ИТОГО", "Распределение", "Проверок")):
        put([line.split()[0] if line.startswith(("OK", "FAIL")) else "", line[5:] if line.startswith(("OK", "FAIL")) else line],
            B if line.startswith("FAIL") else None)
r += 1
put(["Сравнение с сентябрем: выполнение таргета капитализации"], H)
put(["ФОТ — по середине вилки зарплатной группы (HR-группировки); отпуск = OPEX. Таргет HR-расчета: 70% ФОТ, 77% списанных часов."])
for line in tgt.splitlines()[:11]:
    put([line])
r += 1
put(["Сравнение с сентябрем: соблюдение правил"], H)
put(["Правило", "Сентябрь", "Октябрь"], B, fill)
for row in [
    ("≥ 2 CAPEX-задач у сотрудников с CAPEX", "67 из 87 — одна CAPEX-задача", "у всех 90"),
    ("≤ 350 ч на задачу", "соблюдено", "соблюдено"),
    ("Часы по задаче ≤ ёмкости периода работ", "1 нарушение (Руденов: отпуск в начале, даты не сдвинуты)", "соблюдено"),
    ("Нет параллельной перегрузки по срокам", "14 сотрудников (дизайнеры: 176 ч в 8 раб. днях)", "соблюдено"),
    ("Доли по ролям", "4 отклонения (системные аналитики, тестировщик — OPEX-добор)", "соблюдено"),
    ("Задачи чужой должности", "нет", "5 строк соседнего грейда (тестировщики) + исключение Клименко"),
    ("Заголовки колонок", "«Вид работ» и «Задача» перепутаны", "значения под своими заголовками"),
    ("Задачи на замену", "не применены (старые наименования)", "применены (ADTHPL-150/151)"),
]:
    put(list(row))
ws.column_dimensions["A"].width = 44
ws.column_dimensions["B"].width = 110
ws.column_dimensions["C"].width = 50
wb.save(OUT)
print("ok")

const B = (text, ref = 'bul') => new Paragraph({ numbering: { reference: ref, level: 0 }, children: runs(text), spacing: { after: 80 } });
const border = { style: BorderStyle.SINGLE, size: 4, color: LINE };
const borders = { top: border, bottom: border, left: border, right: border };
function table(widths, rows, opts = {}) {
  const total = widths.reduce((a, b) => a + b, 0);
  return new Table({
    width: { size: total, type: WidthType.DXA }, columnWidths: widths,
    rows: rows.map((r, ri) => new TableRow({
      tableHeader: ri === 0, cantSplit: true,
      children: r.map((c, ci) => {
        const hdr = ri === 0; const hl = opts.highlight && opts.highlight.includes(ri);
        return new TableCell({
          width: { size: widths[ci], type: WidthType.DXA }, borders,
          shading: hdr ? { type: ShadingType.CLEAR, color: 'auto', fill: 'EDEDED' } : (hl ? { type: ShadingType.CLEAR, color: 'auto', fill: 'FFF2CC' } : undefined),
          margins: { top: 60, bottom: 60, left: 100, right: 100 },
          children: String(c).split('\n').map(line => new Paragraph({
            children: runs(line, { size: 20, bold: hdr || (hl && opts.boldHighlight) }),
            alignment: (opts.right && opts.right.includes(ci) && !hdr) ? AlignmentType.RIGHT : AlignmentType.LEFT,
            spacing: { after: 0 } })),
        });
      }),
    })),
  });
}

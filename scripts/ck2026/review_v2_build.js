// "**bold**" -> runs
function runs(text, opts = {}) {
  const out = []; const parts = text.split(/(\*\*[^*]+\*\*)/);
  for (const p of parts) {
    if (!p) continue;
    const b = p.startsWith('**') && p.endsWith('**');
    out.push(new TextRun({ text: b ? p.slice(2, -2) : p, bold: b || opts.bold, color: opts.color, size: opts.size, italics: opts.italics }));
  }
  return out;
}
